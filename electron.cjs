app.commandLine.appendSwitch('enable-gpu-rasterization');
app.commandLine.appendSwitch('enable-oop-rasterization');
app.commandLine.appendSwitch('ignore-gpu-blocklist');
app.commandLine.appendSwitch('disable-renderer-backgrounding');
app.commandLine.appendSwitch('disable-background-timer-throttling');
app.commandLine.appendSwitch('force-gpu-mem-available-mb', '2048');


// ─── Updater Configuration ───────────────────────────────────────────────────
autoUpdater.autoDownload = true;
autoUpdater.autoInstallOnAppQuit = true;
autoUpdater.allowDowngrade = false;

// Suppress default electron-updater dialogs
autoUpdater.logger = null;

// In production, electron-updater reads app-update.yml generated by electron-builder.
// Keep the feed config in build metadata so public OTA URLs stay consistent across builds.

let mainWindow = null;

// ─── Helper: Send update status to renderer ──────────────────────────────────
function sendUpdateStatus(status, percent = 0, message = '') {
    if (mainWindow && !mainWindow.isDestroyed()) {
        mainWindow.webContents.send('update-status', { status, percent, message });
    }
}

// ─── Helper: Kill ghost processes ────────────────────────────────────────────
function killGhostProcesses() {
    return new Promise((resolve) => {
        const appName = path.basename(process.execPath, '.exe');
        const currentPid = process.pid;

        // Kill any lingering instances of the app except the current process
        exec(
            `tasklist /FI "IMAGENAME eq ${appName}.exe" /FO CSV /NH`,
            (err, stdout) => {
                if (err || !stdout.trim()) {
                    resolve();
                    return;
                }

                const lines = stdout.trim().split('\n');
                const pidsToKill = [];

                for (const line of lines) {
                    const match = line.match(/"[^"]*","(\d+)"/);
                    if (match) {
                        const pid = parseInt(match[1], 10);
                        if (pid !== currentPid) {
                            pidsToKill.push(pid);
                        }
                    }
                }

                if (pidsToKill.length === 0) {
                    resolve();
                    return;
                }

                console.log(`[OTA] Killing ${pidsToKill.length} ghost process(es):`, pidsToKill);
                const killCmd = pidsToKill.map(pid => `taskkill /PID ${pid} /F`).join(' & ');
                exec(killCmd, () => {
                    // Small delay to let OS release file locks
                    setTimeout(resolve, 500);
                });
            }
        );
    });
}

// ─── Auto-Updater Event Handlers ─────────────────────────────────────────────
autoUpdater.on('checking-for-update', () => {
    console.log('[OTA] Checking for updates...');
    sendUpdateStatus('checking');
});

autoUpdater.on('update-available', (info) => {
    console.log('[OTA] Update available:', info.version);
    sendUpdateStatus('available', 0, `v${info.version} available`);
});

autoUpdater.on('update-not-available', () => {
    console.log('[OTA] App is up to date.');
    sendUpdateStatus('not-available');
});

autoUpdater.on('download-progress', (progress) => {
    const percent = Math.round(progress.percent);
    console.log(`[OTA] Downloading: ${percent}%`);
    sendUpdateStatus('downloading', percent, `${percent}%`);
});

autoUpdater.on('update-downloaded', (info) => {
    console.log('[OTA] Update downloaded:', info.version);
    sendUpdateStatus('downloaded', 100, `v${info.version} ready`);
});

autoUpdater.on('error', (err) => {
    console.error('[OTA] Update error:', err.message);
    sendUpdateStatus('error', 0, err.message);
});

// ─── IPC Handlers ────────────────────────────────────────────────────────────
ipcMain.on('get-app-version', (event) => {
    event.returnValue = app.getVersion();
});

ipcMain.on('install-update', async () => {
    console.log('[OTA] Install requested — killing ghost processes then installing...');
    await killGhostProcesses();
    // isSilent = true, isForceRunAfter = true
    autoUpdater.quitAndInstall(true, true);
});

ipcMain.on('app-quit', () => {
    app.quit();
});

// ─── Window Control IPC ───────────────────────────────────────────────────────
ipcMain.on('window-minimize', () => {
    if (mainWindow) mainWindow.minimize();
});

ipcMain.on('window-maximize', () => {
    if (!mainWindow) return;
    if (mainWindow.isMaximized()) {
        mainWindow.unmaximize();
    } else {
        mainWindow.maximize();
    }
});

ipcMain.on('window-close', () => {
    if (mainWindow) mainWindow.close();
});

ipcMain.handle('window-is-maximized', () => {
    return mainWindow ? mainWindow.isMaximized() : false;
});

// Constrain shell.openPath to a small allowlist of app-owned base directories so
// a compromised renderer cannot ask the OS to open arbitrary local files (e.g. an
// executable on a mounted share). The only legitimate caller opens the app data
// folder ("./data" / the backend-reported data-folder path), all of which resolve
// under cwd / userData / downloads. Anything that escapes those bases is rejected.
const getOpenPathAllowedBases = () => {
    const bases = new Set();
    const add = (p) => {
        if (!p) return;
        try {
            bases.add(path.resolve(p));
        } catch {
            /* ignore unresolved paths */
        }
    };
    add(process.cwd());
    add(__dirname);
    try { add(app.getAppPath()); } catch { /* may be unavailable */ }
    for (const name of ['userData', 'downloads', 'documents', 'temp']) {
        try { add(app.getPath(name)); } catch { /* path not available on platform */ }
    }
    return [...bases];
};

const isPathWithinAllowedBase = (resolvedPath) => {
    return getOpenPathAllowedBases().some((base) => {
        if (resolvedPath === base) return true;
        const baseWithSep = base.endsWith(path.sep) ? base : base + path.sep;
        return resolvedPath.startsWith(baseWithSep);
    });
};

ipcMain.handle('shell-open-path', async (_event, filePath) => {
    if (typeof filePath !== 'string' || !filePath.trim()) {
        console.warn('[Electron] Blocked shell-open-path: invalid path');
        return 'Invalid path';
    }

    let resolved;
    try {
        // Resolve relative inputs against cwd and collapse any ".." segments so
        // traversal cannot escape an allowed base directory.
        resolved = path.resolve(filePath);
    } catch {
        console.warn('[Electron] Blocked shell-open-path: unresolved path');
        return 'Invalid path';
    }

    if (!isPathWithinAllowedBase(resolved)) {
        console.warn('[Electron] Blocked shell-open-path outside allowed directories');
        return 'Path not allowed';
    }

    return shell.openPath(resolved);
});

const isAllowedExternalUrl = (value) => {
    if (typeof value !== 'string') return false;
    try {
        const parsed = new URL(value);
        return parsed.protocol === 'https:' || parsed.protocol === 'http:';
    } catch {
        return false;
    }
};

ipcMain.handle('shell-open-external', async (_event, url) => {
    if (!isAllowedExternalUrl(url)) {
        console.warn('[Electron] Blocked external URL with unsupported scheme');
        return false;
    }
    return shell.openExternal(url);
});

ipcMain.on('set-window-title', (_event, title) => {
    if (mainWindow && !mainWindow.isDestroyed()) {
        mainWindow.setTitle(typeof title === 'string' ? title : 'RTX Terminal');
    }
});

// ─── Window Creation ─────────────────────────────────────────────────────────
function createWindow() {
    mainWindow = new BrowserWindow({
        width: 1400,
        height: 900,
        minWidth: 1024,
        minHeight: 600,
        title: 'RTX Terminal',
        icon: path.join(__dirname, 'build', 'icon.ico'),
        frame: false,
        webPreferences: {
            nodeIntegration: false,
            contextIsolation: true,
            webSecurity: true,
            preload: path.join(__dirname, 'preload.cjs'),
        },
        autoHideMenuBar: true,
        backgroundColor: '#1e1e1e',
    });

    // Notify renderer when maximize state changes
    mainWindow.on('maximize', () => {
        if (mainWindow && !mainWindow.isDestroyed()) {
            mainWindow.webContents.send('window-maximized', true);
        }
    });
    mainWindow.on('unmaximize', () => {
        if (mainWindow && !mainWindow.isDestroyed()) {
            mainWindow.webContents.send('window-maximized', false);
        }
    });

    // In production, load the built files
    mainWindow.loadFile(path.join(__dirname, 'dist', 'index.html'));

    mainWindow.on('closed', () => {
        mainWindow = null;
    });

    // ─── Schedule Update Checks ──────────────────────────────────────────────
    // Initial check after 5 seconds
    setTimeout(() => {
        console.log('[OTA] Running startup update check...');
        autoUpdater.checkForUpdates().catch((err) => {
            console.error('[OTA] Startup check failed:', err.message);
        });
    }, 5000);

    // Periodic check every 60 minutes
    setInterval(() => {
        console.log('[OTA] Running periodic update check...');
        autoUpdater.checkForUpdates().catch((err) => {
            console.error('[OTA] Periodic check failed:', err.message);
        });
    }, 60 * 60 * 1000);
}

// ─── App Lifecycle ───────────────────────────────────────────────────────────
app.whenReady().then(createWindow);

app.on('window-all-closed', () => {
    if (process.platform !== 'darwin') {
        app.quit();
    }
});

app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) {
        createWindow();
    }
});
